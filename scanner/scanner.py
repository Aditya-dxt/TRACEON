"""
scanner/scanner.py

Core engine implementation for Traceon model and dataset scanning.
Enforces the strict contract defined in contracts/scan_result.schema.json.
Rules:
- NEVER executes or imports untrusted artifacts.
- NEVER raises an exception on a bad, malformed, or hostile file; returns an error/fail check instead.
- NEVER assigns a policy verdict (verdicts are exclusively generated by the backend policy engine).
"""

import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any, List, Optional

from scanner.format_detect import compute_sha256_and_size, detect_format
from scanner.pickle_scan import PickleOpcodeScanner
from scanner.safetensors_verify import SafetensorsVerifier
from scanner.gguf_verify import GGUFVerifier
from scanner.onnx_verify import ONNXVerifier
from scanner.dataset_guard import DatasetGuard
from scanner.weights import WeightAnalyzer
from scanner.bom import generate_bom as bom_generator
from scanner.config import MAX_FILE_SIZE_BYTES

ENGINE_VERSION = "0.1.0"


def scan_artifact(path: str, base_model_path: Optional[str] = None) -> Dict[str, Any]:
    """
    Scans a model artifact (pickle, safetensors, pytorch zip, onnx, etc.)
    Returns a dictionary conforming to contracts/scan_result.schema.json.
    Never raises an exception on corrupted or hostile files.
    """
    started_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    scan_id = f"sc_{uuid.uuid4().hex[:8]}"
    file_path = Path(path)
    base_path = Path(base_model_path) if base_model_path else None

    checks_run = []
    findings = []

    # 1. Path existence and basic safety check
    if not file_path.exists():
        completed_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        return {
            "scan_id": scan_id,
            "engine_version": ENGINE_VERSION,
            "artifact": {
                "name": file_path.name,
                "size_bytes": 0,
                "sha256": "0" * 64,
                "detected_format": "unknown"
            },
            "checks_run": [
                {"name": "file_presence", "status": "error", "details": "File does not exist"}
            ],
            "findings": [
                {
                    "finding_id": "f_not_found",
                    "check": "file_presence",
                    "category": "serialization",
                    "severity": "high",
                    "confidence": "high",
                    "deterministic": True,
                    "title": f"Target file not found: {path}",
                    "evidence": {"path": path},
                    "recommendation": "Verify artifact file path."
                }
            ],
            "started_at": started_at,
            "completed_at": completed_at
        }

    try:
        # 2. Format detection & streaming SHA-256
        sha256, size_bytes = compute_sha256_and_size(file_path)
        format_str, format_meta = detect_format(file_path)
        checks_run.append({"name": "format_detect", "status": "pass"})

        # Check maximum file size threshold
        if size_bytes > MAX_FILE_SIZE_BYTES:
            findings.append({
                "finding_id": "f_file_too_large",
                "check": "format_detect",
                "category": "serialization",
                "severity": "medium",
                "confidence": "high",
                "deterministic": True,
                "title": f"Artifact exceeds max file size limit ({size_bytes} > {MAX_FILE_SIZE_BYTES})",
                "evidence": {"file": file_path.name, "size_bytes": size_bytes},
                "recommendation": "Configure extended memory worker for oversized models."
            })

        # 3. Format-specific scans
        if format_str in ("pickle", "pytorch_zip"):
            pickle_scanner = PickleOpcodeScanner()
            p_status, p_findings = pickle_scanner.scan_file(file_path, sha256)
            checks_run.append({"name": "pickle_opcode", "status": p_status})
            findings.extend(p_findings)
            checks_run.append({"name": "safetensors_verify", "status": "skipped"})
            checks_run.append({"name": "weight_stats", "status": "skipped"})

        elif format_str == "safetensors":
            checks_run.append({"name": "pickle_opcode", "status": "skipped"})
            st_verifier = SafetensorsVerifier()
            st_status, st_findings = st_verifier.verify_file(file_path, sha256)
            checks_run.append({"name": "safetensors_verify", "status": st_status})
            findings.extend(st_findings)

            # If Safetensors is structurally valid, analyze tensor weights
            if st_status == "pass":
                weight_analyzer = WeightAnalyzer()
                w_status, w_findings = weight_analyzer.analyze_safetensors_weights(
                    file_path, sha256, base_model_path=base_path
                )
                checks_run.append({"name": "weight_stats", "status": w_status})
                findings.extend(w_findings)
            else:
                checks_run.append({"name": "weight_stats", "status": "skipped"})

        elif format_str == "gguf":
            checks_run.append({"name": "pickle_opcode", "status": "skipped"})
            checks_run.append({"name": "safetensors_verify", "status": "skipped"})
            checks_run.append({"name": "weight_stats", "status": "skipped"})
            gguf_verifier = GGUFVerifier()
            g_status, g_findings = gguf_verifier.verify_file(file_path, sha256)
            checks_run.append({"name": "gguf_verify", "status": g_status})
            findings.extend(g_findings)

        elif format_str == "onnx":
            checks_run.append({"name": "pickle_opcode", "status": "skipped"})
            checks_run.append({"name": "safetensors_verify", "status": "skipped"})
            checks_run.append({"name": "weight_stats", "status": "skipped"})
            onnx_verifier = ONNXVerifier()
            o_status, o_findings = onnx_verifier.verify_file(file_path, sha256)
            checks_run.append({"name": "onnx_verify", "status": o_status})
            findings.extend(o_findings)

        else:
            # Fallback for unknown / other formats
            # Run pickle opcode check in case file is misnamed pickle
            pickle_scanner = PickleOpcodeScanner()
            p_status, p_findings = pickle_scanner.scan_file(file_path, sha256)
            if any(f.get("severity") in ("critical", "high") for f in p_findings):
                checks_run.append({"name": "pickle_opcode", "status": p_status})
                findings.extend(p_findings)
            else:
                checks_run.append({"name": "unsupported_format", "status": "warn"})
                findings.append({
                    "finding_id": "f_unsupported_fmt",
                    "check": "format_detect",
                    "category": "serialization",
                    "severity": "low",
                    "confidence": "high",
                    "deterministic": True,
                    "title": f"Unrecognized model format: {format_str}",
                    "evidence": {"file": file_path.name, "format": format_str, "sha256": sha256},
                    "recommendation": "Use approved formats like Safetensors."
                })

    except Exception as e:
        checks_run.append({"name": "scanner_engine", "status": "error", "details": str(e)})
        findings.append({
            "finding_id": "f_scanner_err",
            "check": "scanner_engine",
            "category": "serialization",
            "severity": "high",
            "confidence": "high",
            "deterministic": True,
            "title": f"Unexpected error during scan: {str(e)}",
            "evidence": {"error": str(e), "file": file_path.name},
            "recommendation": "Review scan worker logs."
        })
        format_str = "error"
        sha256 = "0" * 64
        size_bytes = 0

    completed_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return {
        "scan_id": scan_id,
        "engine_version": ENGINE_VERSION,
        "artifact": {
            "name": file_path.name,
            "size_bytes": size_bytes,
            "sha256": sha256,
            "detected_format": format_str
        },
        "checks_run": checks_run,
        "findings": findings,
        "started_at": started_at,
        "completed_at": completed_at
    }


def scan_dataset(path: str) -> Dict[str, Any]:
    """
    Scans a dataset directory or bundle for unexpected scripts, file types, and integrity.
    Returns a dictionary conforming to contracts/scan_result.schema.json.
    """
    started_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    scan_id = f"sc_{uuid.uuid4().hex[:8]}"
    dir_path = Path(path)

    checks_run = []
    findings = []

    if not dir_path.exists() or not dir_path.is_dir():
        completed_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        return {
            "scan_id": scan_id,
            "engine_version": ENGINE_VERSION,
            "artifact": {
                "name": dir_path.name,
                "size_bytes": 0,
                "sha256": "0" * 64,
                "detected_format": "dataset_directory"
            },
            "checks_run": [
                {"name": "dataset_presence", "status": "error"}
            ],
            "findings": [
                {
                    "finding_id": "f_ds_not_found",
                    "check": "dataset_guard",
                    "category": "dataset",
                    "severity": "high",
                    "confidence": "high",
                    "deterministic": True,
                    "title": f"Dataset directory not found: {path}",
                    "evidence": {"path": path},
                    "recommendation": "Verify dataset path exists."
                }
            ],
            "started_at": started_at,
            "completed_at": completed_at
        }

    try:
        guard = DatasetGuard()
        status, ds_findings, meta = guard.scan_directory(dir_path)
        checks_run.append({"name": "dataset_guard", "status": status})
        findings.extend(ds_findings)
        size_bytes = meta["size_bytes"]
    except Exception as e:
        checks_run.append({"name": "dataset_guard", "status": "error"})
        findings.append({
            "finding_id": "f_ds_err",
            "check": "dataset_guard",
            "category": "dataset",
            "severity": "high",
            "confidence": "high",
            "deterministic": True,
            "title": f"Dataset guard execution failure: {str(e)}",
            "evidence": {"error": str(e)},
            "recommendation": "Inspect dataset permissions."
        })
        size_bytes = 0

    completed_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return {
        "scan_id": scan_id,
        "engine_version": ENGINE_VERSION,
        "artifact": {
            "name": dir_path.name,
            "size_bytes": size_bytes,
            "sha256": "dir_aggregate",
            "detected_format": "dataset_directory"
        },
        "checks_run": checks_run,
        "findings": findings,
        "started_at": started_at,
        "completed_at": completed_at
    }


def generate_bom(model_meta: Dict[str, Any], scan_results: Optional[List[Dict[str, Any]]] = None) -> Dict[str, Any]:
    """Generates CycloneDX 1.7 compliant AI-BOM."""
    return bom_generator(model_meta, scan_results)
